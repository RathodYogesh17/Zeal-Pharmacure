import React, { useState, useEffect, useMemo } from 'react';
import {
  X,
  Send,
  ExternalLink,
  MessageSquare,
  User,
  Phone,
  Mail,
  FileText,
  AlertCircle,
  Sparkles,
  CheckCircle2,
} from 'lucide-react';
import type { IEnquiry, EnquiryStatus } from '../../types';
import {
  buildStatusWhatsAppMessage,
  type WhatsAppEnquiryCategory,
  type WhatsAppTemplateDetails,
} from '../common/whatsapp';

export interface StatusChangeConfirmModalProps {
  isOpen: boolean;
  onClose: () => void;
  enquiry: IEnquiry | null;
  newStatus: EnquiryStatus;
  onConfirm: (
    id: string,
    newStatus: EnquiryStatus,
    note?: string,
    customMessage?: string
  ) => Promise<void>;
  isSubmitting?: boolean;
}

export const StatusChangeConfirmModal: React.FC<StatusChangeConfirmModalProps> = ({
  isOpen,
  onClose,
  enquiry,
  newStatus,
  onConfirm,
  isSubmitting = false,
}) => {
  const [internalNote, setInternalNote] = useState('');
  const [customMessage, setCustomMessage] = useState('');
  const [isEditingMessage, setIsEditingMessage] = useState(false);

  // Determine category & extract details
  const category: WhatsAppEnquiryCategory = useMemo(() => {
    if (!enquiry) return 'PRODUCT';
    const isCareer =
      enquiry.enquiryType === 'CAREER' ||
      enquiry.enquiryCategory === 'CAREER' ||
      Boolean(enquiry.positionAppliedFor);
    if (isCareer) return 'CAREER';

    const isFranchise =
      enquiry.enquiryType === 'FRANCHISE' ||
      enquiry.enquiryCategory === 'FRANCHISE' ||
      Boolean(enquiry.territoryDistrict || enquiry.preferredTerritory);
    if (isFranchise) return 'FRANCHISE';

    return 'PRODUCT';
  }, [enquiry]);

  const clientName = enquiry?.name || enquiry?.fullName || 'Valued Associate';
  const clientPhone = enquiry?.phone || enquiry?.whatsappNumber || '';
  const clientEmail = enquiry?.email || '';
  const refId = enquiry?._id || '';

  const referenceTitle = useMemo(() => {
    if (!enquiry) return '';
    if (category === 'CAREER') {
      return enquiry.positionAppliedFor || 'Pharmaceutical Career Opening';
    }
    if (category === 'FRANCHISE') {
      return (
        enquiry.territoryDistrict ||
        enquiry.preferredTerritory ||
        enquiry.district ||
        enquiry.city ||
        'Designated Territory'
      );
    }
    if (typeof enquiry.product === 'object' && enquiry.product?.name) {
      return enquiry.product.name;
    }
    if (enquiry.products && enquiry.products.length > 0) {
      const first = enquiry.products[0];
      const firstName =
        typeof first.product === 'object' && first.product?.name ? first.product.name : 'Formulation';
      return enquiry.products.length > 1
        ? `${firstName} + ${enquiry.products.length - 1} more items`
        : firstName;
    }
    return 'Pharmaceutical Formulation Requirement';
  }, [enquiry, category]);

  const details: WhatsAppTemplateDetails = useMemo(() => {
    if (!enquiry) return {};
    const qtyStr = enquiry.quantity
      ? `${enquiry.quantity} ${enquiry.quantityUnit || 'Units'}`.trim()
      : undefined;

    let packagingStr = undefined;
    let productMrp = undefined;
    if (typeof enquiry.product === 'object' && enquiry.product) {
      packagingStr = [enquiry.product.dosageForm, enquiry.product.packaging]
        .filter(Boolean)
        .join(' - ');
      if ('mrp' in enquiry.product && (enquiry.product as any).mrp) {
        productMrp = (enquiry.product as any).mrp;
      }
    }

    return {
      packaging: packagingStr,
      mrp: productMrp,
      quantity: qtyStr,
      companyName: enquiry.companyName || undefined,
      city: enquiry.city || undefined,
      state: enquiry.state || undefined,
      drugLicenseNumber: enquiry.drugLicenseNumber || undefined,
      gstNumber: enquiry.gstNumber || undefined,
      investmentBudget: enquiry.investmentBudget || undefined,
      interestedDivisions: enquiry.interestedDivisions?.join(', ') || undefined,
      qualification: enquiry.qualification || undefined,
      experience: enquiry.totalExperienceYears || undefined,
      note: internalNote.trim() || undefined,
    };
  }, [enquiry, internalNote]);

  // Generate the ultra-professional message automatically
  const autoGeneratedMessage = useMemo(() => {
    if (!enquiry || !newStatus) return '';
    return buildStatusWhatsAppMessage({
      category,
      name: clientName,
      phone: clientPhone,
      email: clientEmail,
      refId,
      status: newStatus,
      title: referenceTitle,
      details,
    });
  }, [category, clientName, clientPhone, clientEmail, refId, newStatus, referenceTitle, details]);

  // Keep custom message in sync with auto-generated message when not manually edited
  useEffect(() => {
    if (!isEditingMessage) {
      setCustomMessage(autoGeneratedMessage);
    }
  }, [autoGeneratedMessage, isEditingMessage]);

  // Reset form when modal opens
  useEffect(() => {
    if (isOpen) {
      setInternalNote('');
      setIsEditingMessage(false);
    }
  }, [isOpen]);

  if (!isOpen || !enquiry) return null;

  const handleConfirmClick = async () => {
    await onConfirm(
      enquiry._id,
      newStatus,
      internalNote.trim() || undefined,
      customMessage !== autoGeneratedMessage ? customMessage.trim() : undefined
    );
  };

  const getStatusBadgeColor = (st: string) => {
    switch (st) {
      case 'APPROVED':
      case 'OFFERED':
      case 'HIRED':
      case 'CLOSED':
        return { bg: '#ECFDF5', color: '#065F46', border: '#A7F3D0' };
      case 'QUALIFIED':
      case 'SHORTLISTED':
      case 'QUOTED':
        return { bg: '#EFF6FF', color: '#1E40AF', border: '#BFDBFE' };
      case 'CONTACTED':
      case 'IN_PROGRESS':
      case 'INTERVIEW_SCHEDULED':
        return { bg: '#F5F3FF', color: '#5B21B6', border: '#DDD6FE' };
      case 'DOCUMENTS_PENDING':
      case 'FOLLOW_UP':
      case 'ON_HOLD':
        return { bg: '#FFFBEB', color: '#92400E', border: '#FDE68A' };
      case 'REJECTED':
        return { bg: '#FEF2F2', color: '#991B1B', border: '#FECACA' };
      default:
        return { bg: '#F8FAFC', color: '#334155', border: '#CBD5E1' };
    }
  };

  const oldMeta = getStatusBadgeColor(enquiry.status || 'NEW');
  const newMeta = getStatusBadgeColor(newStatus);

  return (
    <div
      style={{
        position: 'fixed',
        top: 0,
        left: 0,
        right: 0,
        bottom: 0,
        background: 'rgba(15, 23, 42, 0.75)',
        backdropFilter: 'blur(6px)',
        zIndex: 99999,
        display: 'flex',
        alignItems: 'center',
        justifyContent: 'center',
        padding: '16px',
        animation: 'fadeIn 0.2s ease',
      }}
      onClick={(e) => {
        if (e.target === e.currentTarget && !isSubmitting) onClose();
      }}
    >
      <div
        style={{
          background: '#FFFFFF',
          borderRadius: '20px',
          width: '100%',
          maxWidth: '750px',
          maxHeight: '92vh',
          display: 'flex',
          flexDirection: 'column',
          boxShadow: '0 25px 60px -15px rgba(0, 0, 0, 0.35)',
          border: '1.5px solid #E2E8F0',
          overflow: 'hidden',
        }}
      >
        {/* Header */}
        <div
          style={{
            padding: '20px 24px',
            borderBottom: '1.5px solid #F1F5F9',
            display: 'flex',
            alignItems: 'center',
            justifyContent: 'space-between',
            background: 'linear-gradient(180deg, #F8FAFC 0%, #FFFFFF 100%)',
          }}
        >
          <div style={{ display: 'flex', alignItems: 'center', gap: '12px' }}>
            <div
              style={{
                width: '42px',
                height: '42px',
                borderRadius: '12px',
                background: '#ECFDF5',
                border: '1.5px solid #A7F3D0',
                color: '#059669',
                display: 'flex',
                alignItems: 'center',
                justifyContent: 'center',
              }}
            >
              <Send size={20} />
            </div>
            <div>
              <h2 style={{ fontSize: '18px', fontWeight: 800, color: '#0F172A', margin: 0 }}>
                Confirm Status &amp; Dispatch WhatsApp
              </h2>
              <p style={{ fontSize: '12.5px', color: '#64748B', margin: '2px 0 0' }}>
                Status will be saved &amp; professional message sent directly to applicant
              </p>
            </div>
          </div>

          <button
            type="button"
            onClick={onClose}
            disabled={isSubmitting}
            style={{
              background: '#F1F5F9',
              border: 'none',
              borderRadius: '10px',
              width: '34px',
              height: '34px',
              display: 'flex',
              alignItems: 'center',
              justifyContent: 'center',
              color: '#64748B',
              cursor: isSubmitting ? 'not-allowed' : 'pointer',
            }}
          >
            <X size={18} />
          </button>
        </div>

        {/* Scrollable Body */}
        <div
          style={{
            padding: '20px 24px',
            overflowY: 'auto',
            display: 'flex',
            flexDirection: 'column',
            gap: '16px',
            flex: 1,
          }}
        >
          {/* Status Transition Banner */}
          <div
            style={{
              padding: '14px 18px',
              background: '#F8FAFC',
              borderRadius: '14px',
              border: '1.5px solid #E2E8F0',
              display: 'flex',
              alignItems: 'center',
              justifyContent: 'space-between',
              flexWrap: 'wrap',
              gap: '12px',
            }}
          >
            <div>
              <div style={{ fontSize: '11px', fontWeight: 700, color: '#64748B', textTransform: 'uppercase' }}>
                Pipeline Transition
              </div>
              <div style={{ display: 'flex', alignItems: 'center', gap: '8px', marginTop: '6px' }}>
                <span
                  style={{
                    background: oldMeta.bg,
                    color: oldMeta.color,
                    border: `1px solid ${oldMeta.border}`,
                    padding: '3px 10px',
                    borderRadius: '8px',
                    fontSize: '12px',
                    fontWeight: 700,
                  }}
                >
                  {enquiry.status || 'NEW'}
                </span>
                <span style={{ color: '#94A3B8', fontWeight: 800 }}>➔</span>
                <span
                  style={{
                    background: newMeta.bg,
                    color: newMeta.color,
                    border: `1.5px solid ${newMeta.border}`,
                    padding: '4px 12px',
                    borderRadius: '8px',
                    fontSize: '13px',
                    fontWeight: 800,
                  }}
                >
                  {newStatus}
                </span>
              </div>
            </div>

            {/* Direct WhatsApp Status */}
            <div style={{ display: 'flex', alignItems: 'center', gap: '8px' }}>
              <span
                style={{
                  width: '8px',
                  height: '8px',
                  borderRadius: '50%',
                  background: '#10B981',
                  boxShadow: '0 0 6px #10B981',
                }}
              />
              <span
                style={{
                  fontSize: '12px',
                  fontWeight: 700,
                  color: '#065F46',
                }}
              >
                💬 WhatsApp Click-to-Chat (1-Click Send)
              </span>
            </div>
          </div>

          {/* Applicant Summary Card */}
          <div
            style={{
              padding: '12px 16px',
              borderRadius: '12px',
              background: '#F1F5F9',
              border: '1px solid #E2E8F0',
              display: 'grid',
              gridTemplateColumns: 'repeat(auto-fit, minmax(200px, 1fr))',
              gap: '8px 16px',
              fontSize: '12.5px',
            }}
          >
            <div style={{ display: 'flex', alignItems: 'center', gap: '6px' }}>
              <User size={14} style={{ color: '#64748B' }} />
              <span style={{ fontWeight: 700, color: '#1E293B' }}>{clientName}</span>
            </div>
            <div style={{ display: 'flex', alignItems: 'center', gap: '6px' }}>
              <Phone size={14} style={{ color: '#059669' }} />
              <span style={{ fontWeight: 600, color: '#059669' }}>+{clientPhone}</span>
            </div>
            <div style={{ display: 'flex', alignItems: 'center', gap: '6px' }}>
              <Mail size={14} style={{ color: '#64748B' }} />
              <span style={{ color: '#475569', overflow: 'hidden', textOverflow: 'ellipsis' }}>
                {clientEmail || 'Email N/A'}
              </span>
            </div>
            <div style={{ display: 'flex', alignItems: 'center', gap: '6px' }}>
              <FileText size={14} style={{ color: '#6828DC' }} />
              <span style={{ fontWeight: 600, color: '#6828DC' }}>
                #{refId.slice(-8).toUpperCase()} • {referenceTitle}
              </span>
            </div>
          </div>

          {/* Message Preview Box */}
          <div>
            <div
              style={{
                display: 'flex',
                alignItems: 'center',
                justifyContent: 'space-between',
                marginBottom: '8px',
              }}
            >
              <label
                style={{
                  fontSize: '12px',
                  fontWeight: 800,
                  color: '#334155',
                  display: 'flex',
                  alignItems: 'center',
                  gap: '6px',
                }}
              >
                <Sparkles size={14} style={{ color: '#059669' }} />
                <span>Auto-Generated Professional WhatsApp Message</span>
              </label>

              <button
                type="button"
                onClick={() => setIsEditingMessage(!isEditingMessage)}
                style={{
                  background: 'none',
                  border: 'none',
                  color: '#6828DC',
                  fontSize: '12px',
                  fontWeight: 700,
                  cursor: 'pointer',
                  textDecoration: 'underline',
                }}
              >
                {isEditingMessage ? 'Lock Preview' : 'Edit Message'}
              </button>
            </div>

            <textarea
              rows={10}
              value={customMessage}
              readOnly={!isEditingMessage}
              onChange={(e) => {
                setCustomMessage(e.target.value);
                setIsEditingMessage(true);
              }}
              style={{
                width: '100%',
                padding: '14px',
                borderRadius: '12px',
                border: isEditingMessage ? '1.5px solid #6828DC' : '1.5px solid #CBD5E1',
                background: isEditingMessage ? '#FFFFFF' : '#F8FAFC',
                fontSize: '12.5px',
                lineHeight: '1.6',
                color: '#1E293B',
                fontFamily: 'monospace, sans-serif',
                whiteSpace: 'pre-wrap',
                resize: 'vertical',
                boxSizing: 'border-box',
                outline: 'none',
              }}
            />
          </div>

          {/* Optional Internal Note */}
          <div>
            <label
              style={{
                display: 'block',
                fontSize: '12px',
                fontWeight: 700,
                color: '#475569',
                marginBottom: '6px',
              }}
            >
              Internal Admin Note (Saved to History)
            </label>
            <input
              type="text"
              value={internalNote}
              onChange={(e) => setInternalNote(e.target.value)}
              placeholder="e.g. Rate card shared, candidate interview scheduled on Thursday..."
              style={{
                width: '100%',
                padding: '10px 14px',
                borderRadius: '10px',
                border: '1.5px solid #CBD5E1',
                fontSize: '13px',
                color: '#1E293B',
                boxSizing: 'border-box',
                outline: 'none',
              }}
            />
          </div>
        </div>

        {/* Footer Actions */}
        <div
          style={{
            padding: '16px 24px',
            borderTop: '1.5px solid #F1F5F9',
            display: 'flex',
            alignItems: 'center',
            justifyContent: 'space-between',
            background: '#F8FAFC',
            flexWrap: 'wrap',
            gap: '12px',
          }}
        >
          <button
            type="button"
            onClick={onClose}
            disabled={isSubmitting}
            style={{
              padding: '10px 18px',
              borderRadius: '10px',
              border: '1.5px solid #CBD5E1',
              background: '#FFFFFF',
              color: '#475569',
              fontSize: '13px',
              fontWeight: 700,
              cursor: isSubmitting ? 'not-allowed' : 'pointer',
            }}
          >
            Cancel
          </button>

          <button
            type="button"
            onClick={handleConfirmClick}
            disabled={isSubmitting}
            style={{
              padding: '11px 24px',
              borderRadius: '10px',
              border: 'none',
              background: 'linear-gradient(135deg, #059669 0%, #10B981 100%)',
              color: '#FFFFFF',
              fontSize: '13.5px',
              fontWeight: 700,
              display: 'flex',
              alignItems: 'center',
              gap: '8px',
              cursor: isSubmitting ? 'not-allowed' : 'pointer',
              boxShadow: '0 4px 14px rgba(16, 185, 129, 0.35)',
              opacity: isSubmitting ? 0.7 : 1,
            }}
          >
            <Send size={16} />
            <span>
              {isSubmitting
                ? 'Updating Status...'
                : `Confirm Status & Open WhatsApp (${newStatus})`}
            </span>
          </button>
        </div>
      </div>
    </div>
  );
};
